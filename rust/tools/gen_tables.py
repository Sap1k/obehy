"""Writes the Python tables the Rust port reads as code (docs/RUST_PORT.md, R2).

    uv run python rust/tools/gen_tables.py

- obehy-core/src/py/unicode.rs: which characters `str.isdecimal` (with their digit values),
  `str.isdigit` and `str.isspace` accept, from this Python's `unicodedata`, and what
  `str.casefold` maps each character to (full case folding, `names.py`);
- obehy-sources/src/reader/html_entities.rs: `html.entities.html5` and the two tables of
  `html.unescape` (`_invalid_charrefs`, `_invalid_codepoints`).

Regenerate on a Python minor bump (a new Unicode version).
"""

from __future__ import annotations

import html
import sys
import unicodedata
from html.entities import html5
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
UNICODE = REPO / "rust" / "obehy-core" / "src" / "py" / "unicode.rs"
ENTITIES = REPO / "rust" / "obehy-sources" / "src" / "reader" / "html_entities.rs"


def ranges(test: object) -> list[tuple[int, int]]:
    found: list[tuple[int, int]] = []
    start = None
    for cp in range(sys.maxunicode + 2):
        ok = cp <= sys.maxunicode and test(chr(cp))  # type: ignore[operator]
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            found.append((start, cp - 1))
            start = None
    return found


def decimal_runs() -> list[tuple[int, int, int]]:
    runs: list[tuple[int, int, int]] = []
    for lo, hi in ranges(str.isdecimal):
        cp = lo
        while cp <= hi:
            value = unicodedata.decimal(chr(cp))
            end = cp
            while end + 1 <= hi and unicodedata.decimal(chr(end + 1)) == value + (end + 1 - cp):
                end += 1
            runs.append((cp, end, value))
            cp = end + 1
    return runs


def casefold_map() -> list[tuple[int, str]]:
    found: list[tuple[int, str]] = []
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        folded = chr(cp).casefold()
        if folded != chr(cp):
            found.append((cp, folded))
    return found


def rust_string(text: str) -> str:
    plain = (c for c in text)
    return (
        '"'
        + "".join(c if " " <= c <= "~" and c not in '"\\' else f"\\u{{{ord(c):x}}}" for c in plain)
        + '"'
    )


def write_unicode() -> None:
    lines = [
        "//! Generated by rust/tools/gen_tables.py from Python's unicodedata "
        f"{unicodedata.unidata_version}: do not edit.",
        "",
        "/// `str.isdecimal` runs: (first, last, digit value of first).",
        "pub const DECIMAL: &[(u32, u32, u32)] = &[",
        *(f"    (0x{lo:x}, 0x{hi:x}, {v})," for lo, hi, v in decimal_runs()),
        "];",
        "",
        "/// `str.isdigit` ranges (decimals included).",
        "pub const DIGIT: &[(u32, u32)] = &[",
        *(f"    (0x{lo:x}, 0x{hi:x})," for lo, hi in ranges(str.isdigit)),
        "];",
        "",
        "/// `str.isspace` ranges.",
        "pub const SPACE: &[(u32, u32)] = &[",
        *(f"    (0x{lo:x}, 0x{hi:x})," for lo, hi in ranges(str.isspace)),
        "];",
        "",
        "/// `str.casefold` of each character it changes, sorted: full case folding, so one",
        "/// character may fold to several (`ß` to `ss`).",
        "pub const CASEFOLD: &[(u32, &str)] = &[",
        *(f"    (0x{cp:x}, {rust_string(folded)})," for cp, folded in casefold_map()),
        "];",
        "",
    ]
    UNICODE.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_entities() -> None:
    names = sorted(html5)
    invalid = html._invalid_charrefs  # type: ignore[attr-defined]
    codepoints = sorted(html._invalid_codepoints)  # type: ignore[attr-defined]
    lines = [
        "//! Generated by rust/tools/gen_tables.py from Python's html module: do not edit.",
        "",
        "/// `html.entities.html5`, sorted by name.",
        "pub const HTML5: &[(&str, &str)] = &[",
        *(f"    ({rust_string(n)}, {rust_string(html5[n])})," for n in names),
        "];",
        "",
        "/// `html._invalid_charrefs`, sorted.",
        "pub const INVALID_CHARREFS: &[(u32, &str)] = &[",
        *(f"    (0x{k:x}, {rust_string(invalid[k])})," for k in sorted(invalid)),
        "];",
        "",
        "/// `html._invalid_codepoints`, sorted.",
        "pub const INVALID_CODEPOINTS: &[u32] = &[",
        *(f"    0x{c:x}," for c in codepoints),
        "];",
        "",
    ]
    ENTITIES.parent.mkdir(parents=True, exist_ok=True)
    ENTITIES.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    write_unicode()
    write_entities()
    print(f"wrote {UNICODE} and {ENTITIES}")
